"use client";

import { Check, Clock, X, FileText, AlertCircle } from "lucide-react";

interface WorkflowTrackerProps {
  status: string; // PENDING, MANAGER_APPROVED, HR_APPROVED, COMPLETED, REJECTED
  approvals?: Array<{
    id: string;
    level: string; // MANAGER, HR
    action: string; // APPROVED, REJECTED
    approverName?: string | null;
    comments?: string | null;
    createdAt: string | Date;
  }>;
}

export function LetterWorkflowTracker({ status, approvals = [] }: WorkflowTrackerProps) {
  const isRejected = status === "REJECTED";
  const managerApproval = approvals.find((a) => a.level === "MANAGER");
  const hrApproval = approvals.find((a) => a.level === "HR");

  // Step 1: Request Submitted (Always Done)
  // Step 2: Manager Approval
  const isManagerDone = !!managerApproval && managerApproval.action === "APPROVED";
  const isManagerPending = status === "PENDING";
  const isManagerRejected = managerApproval?.action === "REJECTED";

  // Step 3: HR Review & Letter Generation
  const isHrDone = status === "COMPLETED" || (!!hrApproval && hrApproval.action === "APPROVED");
  const isHrPending = status === "MANAGER_APPROVED";
  const isHrRejected = hrApproval?.action === "REJECTED";

  // Step 4: Letter Ready
  const isLetterReady = status === "COMPLETED";

  const steps = [
    {
      title: "Request Submitted",
      desc: "Employee submission verified",
      status: "COMPLETED",
    },
    {
      title: "Manager Approval",
      desc: isManagerDone
        ? `Approved by ${managerApproval?.approverName || "Manager"}`
        : isManagerRejected
        ? `Rejected: ${managerApproval?.comments || "No comments"}`
        : isManagerPending
        ? "Pending Manager Review"
        : "Queued",
      status: isManagerDone ? "COMPLETED" : isManagerRejected ? "REJECTED" : isManagerPending ? "IN_PROGRESS" : "UPCOMING",
    },
    {
      title: "HR Review & Generation",
      desc: isHrDone
        ? `Reviewed & Generated by HR`
        : isHrRejected
        ? `Rejected: ${hrApproval?.comments || "No comments"}`
        : isHrPending
        ? "Pending HR Review"
        : "Queued",
      status: isHrDone ? "COMPLETED" : isHrRejected ? "REJECTED" : isHrPending ? "IN_PROGRESS" : "UPCOMING",
    },
    {
      title: "Letter Ready",
      desc: isLetterReady ? "Official PDF available for download" : "Awaiting approvals",
      status: isLetterReady ? "COMPLETED" : "UPCOMING",
    },
  ];

  return (
    <div className="w-full py-4">
      <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        {steps.map((step, idx) => {
          const isLast = idx === steps.length - 1;
          return (
            <div key={idx} className="flex-1 flex items-center w-full">
              <div className="flex items-center gap-3">
                <div
                  className={`h-9 w-9 rounded-xl flex items-center justify-center font-bold text-xs shadow-sm transition-all ${
                    step.status === "COMPLETED"
                      ? "bg-emerald-500 text-white shadow-emerald-500/20"
                      : step.status === "REJECTED"
                      ? "bg-rose-500 text-white shadow-rose-500/20"
                      : step.status === "IN_PROGRESS"
                      ? "bg-amber-500 text-white shadow-amber-500/20 animate-pulse"
                      : "bg-slate-100 dark:bg-slate-800 text-slate-400"
                  }`}
                >
                  {step.status === "COMPLETED" ? (
                    <Check className="h-4 w-4" />
                  ) : step.status === "REJECTED" ? (
                    <X className="h-4 w-4" />
                  ) : step.status === "IN_PROGRESS" ? (
                    <Clock className="h-4 w-4" />
                  ) : (
                    <span>{idx + 1}</span>
                  )}
                </div>

                <div>
                  <div className="text-xs font-bold text-slate-900 dark:text-white leading-tight">
                    {step.title}
                  </div>
                  <div className="text-[10px] text-slate-400 font-medium leading-tight mt-0.5">
                    {step.desc}
                  </div>
                </div>
              </div>

              {!isLast && (
                <div className="hidden md:block flex-1 mx-4 h-[2px] bg-slate-200 dark:bg-slate-800" />
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}

